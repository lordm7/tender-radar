def main() -> None:
    archive = pymupdf.Archive(FONT_DIR)
    doc = pymupdf.open()
    for html in PAGES:
        page = doc.new_page()
        page.insert_htmlbox(pymupdf.Rect(50, 50, 545, 800), f'<div dir="rtl">{html}</div>', css=CSS, archive=archive)
    doc.set_metadata({"title": "Synthetic sample tender booklet (demo)", "author": "Tender Radar demo"})
    doc.save(OUT)
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
